#!/usr/bin/env python3
"""Generate the checked-in built-in tool governance inventory."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "12-d6-tool-discovery.md"
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agent.tools.job_migration import (
    TOOL_JOB_MIGRATION_PLAN,
    validate_job_migration_plan,
    validate_job_regression_matrix,
)
from agent.tools.registry import BUILTIN_TOOL_REGISTRY
from agent.tools.schemas import AGENT_TOOLS
from agent.tools.exposure import MAX_VISIBLE_TOOLS
from data.session import DISCOVERED_TOOL_TTL_TURNS


def _values(values) -> str:
    return ", ".join(sorted(values)) if values else "-"


def render() -> str:
    BUILTIN_TOOL_REGISTRY.validate_schema_names(AGENT_TOOLS)
    validate_job_migration_plan()
    validate_job_regression_matrix()
    specs = BUILTIN_TOOL_REGISTRY.all()
    lines = [
        "# D6 Tool Discovery Inventory",
        "",
        "<!-- Generated by scripts/generate_tool_inventory.py; do not edit manually. -->",
        "",
        "Generated from `agent.tools.registry.BUILTIN_TOOL_REGISTRY` and "
        "`agent.tools.job_migration.TOOL_JOB_MIGRATION_PLAN`.",
        "",
        f"- Registered built-in tools: {len(specs)}",
        f"- Default-exposed tools: {sum(spec.default_exposed for spec in specs)}",
        f"- Discoverable tools: {sum(spec.discoverable for spec in specs)}",
        f"- Discovery lifetime: latest {DISCOVERED_TOOL_TTL_TURNS} user turns",
        f"- Final model-visible hard cap: {MAX_VISIBLE_TOOLS} tools (including MCP)",
        "",
        "| Tool | Category | Side effect | Confirmation | Default | Discoverable | Commands | Skills | Data | Workspace | Execution | Job policy |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for spec in specs:
        job = TOOL_JOB_MIGRATION_PLAN.get(spec.name)
        lines.append(
            "| {name} | {category} | {side_effect} | {confirmation} | {default} | "
            "{discoverable} | {commands} | {skills} | {data} | {workspace} | "
            "{execution} | {job} |".format(
                name=spec.name,
                category=spec.category,
                side_effect=spec.side_effect,
                confirmation=spec.confirmation,
                default="yes" if spec.default_exposed else "no",
                discoverable="yes" if spec.discoverable else "no",
                commands=_values(spec.commands),
                skills=_values(spec.skills),
                data="yes" if spec.requires_data_source else "no",
                workspace="yes" if spec.requires_workspace else "no",
                execution=spec.execution_mode,
                job=job.status if job else "MISSING",
            )
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check", action="store_true",
        help="fail when the checked-in inventory differs from generated output",
    )
    args = parser.parse_args()
    rendered = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != rendered:
            raise SystemExit(
                "tool inventory is stale; run scripts/generate_tool_inventory.py"
            )
        return 0
    TARGET.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
